TEST(CryptographyNoiseXXHandshake, roundtripTest)
{
	using namespace Noise::NoiseXX;

	// keys to exchange
	Keypair initiatorStaticKeys = generateKeypair_x25519();
	Keypair responderStaticKeys = generateKeypair_x25519();

	// initialize both parts
	Noise::InitiatorHandshakeState initiatorHandshakeState = initializeInitiator(initiatorStaticKeys);
	Noise::ResponderHandshakeState responderHandshakeState = initializeResponder(responderStaticKeys);

	std::array<std::byte, Message2ExpectedSize> messageBuffer = {};
	size_t initiatorCursor = 0;
	EXPECT_EQ(appendHandshakeMessage1(initiatorHandshakeState, messageBuffer, initiatorCursor), std::nullopt);

	size_t receiverCursor = 0;
	EXPECT_EQ(processHandshakeMessage1(responderHandshakeState, messageBuffer, receiverCursor), std::nullopt);

	receiverCursor = 0;
	EXPECT_EQ(appendHandshakeMessage2(responderHandshakeState, messageBuffer, receiverCursor), std::nullopt);

	initiatorCursor = 0;
	EXPECT_EQ(processHandshakeMessage2(initiatorHandshakeState, messageBuffer, initiatorCursor), std::nullopt);

	initiatorCursor = 0;
	const auto result1 = appendHandshakeMessage3(std::move(initiatorHandshakeState), messageBuffer, initiatorCursor);

	receiverCursor = 0;
	const auto result2 = processHandshakeMessage3(std::move(responderHandshakeState), messageBuffer, receiverCursor);

	ASSERT_TRUE(std::holds_alternative<HandshakeResult>(result1));
	ASSERT_TRUE(std::holds_alternative<HandshakeResult>(result2));

	EXPECT_EQ(std::get<HandshakeResult>(result1).chainingKey.raw, std::get<HandshakeResult>(result2).chainingKey.raw);
	EXPECT_EQ(initiatorStaticKeys.publicKey.raw, std::get<HandshakeResult>(result2).remoteStaticKey.raw);
	EXPECT_EQ(std::get<HandshakeResult>(result1).remoteStaticKey.raw, responderStaticKeys.publicKey.raw);
}

static Cryptography::Keypair makeKeypair(const std::string_view secretHex, const std::string_view publicHex)
{
	Cryptography::Keypair keypair;
	const std::vector<std::byte> secret = hexToBytes(secretHex);
	const std::vector<std::byte> publicKey = hexToBytes(publicHex);

	if (secret.size() != keypair.secretKey.raw.size() || publicKey.size() != keypair.publicKey.raw.size())
	{
		ADD_FAILURE() << "Invalid fixed keypair length";
		return keypair;
	}

	std::copy(secret.begin(), secret.end(), keypair.secretKey.raw.begin());
	std::copy(publicKey.begin(), publicKey.end(), keypair.publicKey.raw.begin());
	return keypair;
}

static void writeFixedEphemeral(const Cryptography::Keypair& ephemeralKeys, const std::span<std::byte> outMessageBuffer, size_t& inOutCursor, Noise::SymmetricState& symmetricState)
{
	ASSERT_EQ(Noise::Utils::writeDataToBuffer(ephemeralKeys.publicKey, outMessageBuffer, inOutCursor), 0);
	Noise::Utils::mixHash(ephemeralKeys.publicKey, symmetricState);
}

TEST(CryptographyNoiseXXHandshake, rustReferenceTranscriptTest)
{
	// the results are taken from the reference Rust implementation generated by noiseexplorer.com
	// where Blake2s replaced with Blake2b (with HASHLEN set 64 and BLAKE2b BLOCKLEN to 128)
	// with the same test constructed for that implementation

	using namespace Noise::NoiseXX;

	const Keypair initiatorStaticKeys = makeKeypair(
		"da3a44afb3048f51484f54b38a56522bbeab0e315f1dee07a4a54df4f0da7a20",
		"170eed9741a0a1b43382cdd8f21449cf9762f9d61cbd4ae7dc9f8b17db03371b"
	);
	const Keypair responderStaticKeys = makeKeypair(
		"d2ec0792480dd0efe2850ce84c9d367202e0fb67fe462314c7a9f94ed3911f73",
		"bd918676bb3c2657a264cc1047601ad931b9fb0d5ec42e688ee7b06ce077a777"
	);
	const Keypair initiatorEphemeralKeys = makeKeypair(
		"0102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f20",
		"07a37cbc142093c8b755dc1b10e86cb426374ad16aa853ed0bdfc0b2b86d1c7c"
	);
	const Keypair responderEphemeralKeys = makeKeypair(
		"101112131415161718191a1b1c1d1e1f000102030405060708090a0b0c0d0e0f",
		"a64abe376a73c085bc26d95c60a74bc17c1b389876321ac881e8d07e3e231e45"
	);

	Noise::InitiatorHandshakeState initiatorHandshakeState = initializeInitiator(initiatorStaticKeys);
	Noise::ResponderHandshakeState responderHandshakeState = initializeResponder(responderStaticKeys);

	// -> e
	std::array<std::byte, Message1ExpectedSize> message1 = {};
	size_t initiatorCursor = 0;
	initiatorHandshakeState.ephemeralKeys = initiatorEphemeralKeys.clone();
	writeFixedEphemeral(initiatorEphemeralKeys, message1, initiatorCursor, initiatorHandshakeState.symmetricState);
	ASSERT_EQ(Noise::Utils::appendEmptyPayloadMacAndHash(initiatorHandshakeState.symmetricState, message1, initiatorCursor), 0);
	EXPECT_EQ(initiatorCursor, message1.size());

	size_t responderCursor = 0;
	ASSERT_EQ(Noise::MessagePatterns::readMessagePattern_e_responder(responderHandshakeState, message1, responderCursor), std::nullopt);
	ASSERT_EQ(Noise::Utils::consumeEmptyPayloadMacAndHash(responderHandshakeState.symmetricState, message1, responderCursor), 0);
	EXPECT_EQ(responderCursor, message1.size());
	assertSpansEqual(hexToBytes("07a37cbc142093c8b755dc1b10e86cb426374ad16aa853ed0bdfc0b2b86d1c7c"), message1);

	// <- e, ee, s, es
	std::array<std::byte, Message2ExpectedSize> message2 = {};
	responderCursor = 0;
	responderHandshakeState.ephemeralKeys = responderEphemeralKeys.clone();
	writeFixedEphemeral(responderEphemeralKeys, message2, responderCursor, responderHandshakeState.symmetricState);
	ASSERT_EQ(Noise::MessagePatterns::writeMessagePattern_ee_responder(responderHandshakeState), std::nullopt);
	ASSERT_EQ(Noise::MessagePatterns::writeMessagePattern_s_responder(responderHandshakeState, message2, responderCursor), std::nullopt);
	ASSERT_EQ(Noise::MessagePatterns::writeMessagePattern_es_responder(responderHandshakeState), std::nullopt);
	ASSERT_EQ(Noise::Utils::appendEmptyPayloadMacAndHash(responderHandshakeState.symmetricState, message2, responderCursor), 0);
	EXPECT_EQ(responderCursor, message2.size());

	initiatorCursor = 0;
	ASSERT_EQ(Noise::MessagePatterns::readMessagePattern_e_initiator(initiatorHandshakeState, message2, initiatorCursor), std::nullopt);
	ASSERT_EQ(Noise::MessagePatterns::readMessagePattern_ee_initiator(initiatorHandshakeState), std::nullopt);
	ASSERT_EQ(Noise::MessagePatterns::readMessagePattern_s_initiator(initiatorHandshakeState, message2, initiatorCursor), std::nullopt);
	ASSERT_EQ(Noise::MessagePatterns::readMessagePattern_es_initiator(initiatorHandshakeState), std::nullopt);
	ASSERT_EQ(Noise::Utils::consumeEmptyPayloadMacAndHash(initiatorHandshakeState.symmetricState, message2, initiatorCursor), 0);
	EXPECT_EQ(initiatorCursor, message2.size());
	assertSpansEqual(hexToBytes("a64abe376a73c085bc26d95c60a74bc17c1b389876321ac881e8d07e3e231e45a09463f6f32ef57faceb48a06c15599a65b54645414de626574b9ff49b4ab9b9a1a55dedbc0bfa27d5056eacaaba5b310f604afc3b2cbf6bc5d7a297115878b3"), message2);

	// -> s, se
	std::array<std::byte, Message3ExpectedSize> message3 = {};
	initiatorCursor = 0;
	ASSERT_EQ(Noise::MessagePatterns::writeMessagePattern_s_initiator(initiatorHandshakeState, message3, initiatorCursor), std::nullopt);
	ASSERT_EQ(Noise::MessagePatterns::writeMessagePattern_se_initiator(initiatorHandshakeState), std::nullopt);
	ASSERT_EQ(Noise::Utils::appendEmptyPayloadMacAndHash(initiatorHandshakeState.symmetricState, message3, initiatorCursor), 0);
	EXPECT_EQ(initiatorCursor, message3.size());

	responderCursor = 0;
	ASSERT_EQ(Noise::MessagePatterns::readMessagePattern_s_responder(responderHandshakeState, message3, responderCursor), std::nullopt);
	ASSERT_EQ(Noise::MessagePatterns::readMessagePattern_se_responder(responderHandshakeState), std::nullopt);
	ASSERT_EQ(Noise::Utils::consumeEmptyPayloadMacAndHash(responderHandshakeState.symmetricState, message3, responderCursor), 0);
	EXPECT_EQ(responderCursor, message3.size());
	assertSpansEqual(hexToBytes("9726ae00e10437d5fdc9808e66a9c723f3c4fdab4b9168a32597de1f455436905f3ff69c5e264a5d7563ba154a275deb92d221fd2f7d8cbb26ed8ebc2d27b7c1"), message3);

	const char* expectedHash = "c7738662485e71df0a5119701836ca6ec6799018c1b1ea856f35f0efa78b2c0c68312f261eb27475021495248ff2c372e1900d69b3ed30256fdc3090ef646d2e";
	const char* expectedChainingKey = "a8a42fe72a4e0b1a01cd3bf6d92b83a6de92a24d948612ece30af29501c52bbfc28c0ca1fae68c537edf0d91ee0da34dae6da04db22712414e559c1e31b1d4e1";
	assertSpansEqual(hexToBytes(expectedHash), initiatorHandshakeState.symmetricState.handshakeHash.raw);
	assertSpansEqual(hexToBytes(expectedHash), responderHandshakeState.symmetricState.handshakeHash.raw);
	assertSpansEqual(hexToBytes(expectedChainingKey), initiatorHandshakeState.symmetricState.chainingKey.raw);
	assertSpansEqual(hexToBytes(expectedChainingKey), responderHandshakeState.symmetricState.chainingKey.raw);

	Noise::CipherStateSending initiatorSending;
	Noise::CipherStateReceiving initiatorReceiving;
	Noise::CipherStateSending responderSending;
	Noise::CipherStateReceiving responderReceiving;
	Noise::Utils::split(initiatorHandshakeState.symmetricState, initiatorSending, initiatorReceiving, Noise::Utils::HandshakeRole::Initiator);
	Noise::Utils::split(responderHandshakeState.symmetricState, responderSending, responderReceiving, Noise::Utils::HandshakeRole::Responder);

	const char* expectedC1 = "fca2cc30d9f77955de4db45ee94ebb5904cd2b0fa68989d28ec8fc6d5f4c551e";
	const char* expectedC2 = "3d066f9d5b747524a18344aa34b5831ef212cded73577ee22bec2c514f26ec6e";
	assertSpansEqual(hexToBytes(expectedC1), initiatorSending.cipherKey.raw);
	assertSpansEqual(hexToBytes(expectedC1), responderReceiving.cipherKey.raw);
	assertSpansEqual(hexToBytes(expectedC2), initiatorReceiving.cipherKey.raw);
	assertSpansEqual(hexToBytes(expectedC2), responderSending.cipherKey.raw);
	EXPECT_EQ(initiatorSending.nonce, 0u);
	EXPECT_EQ(initiatorReceiving.nonce, 0u);
	EXPECT_EQ(responderSending.nonce, 0u);
	EXPECT_EQ(responderReceiving.nonce, 0u);
}
